#!/bin/bash -e

# Build data.generated.js (loaded by index.html) from the committed per-version result
# files in results/ (produced by fetch-results.sh) and the query sets in queries/.
#
# Output has two consts:
#   const datasets = [{name, queries:[...]}, ...]   // in the QUERY_ORDER the result
#                                                    // arrays are concatenated in
#   const data     = [{version, actual_version, release_date, machine,
#                      load_time:{ds:sec}, data_size:{ds:bytes}, result:[[...]], source}]
#
# Keeping data out of index.html (as the main ClickBench page does with
# data.generated.js) keeps the page diffable and lets the data regenerate on its own.

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "${HERE}"

# The order the runner concatenates per-dataset query results into result[] (see
# QUERY_ORDER in run-version.sh). datasets[].queries line up with result[] by offset.
QUERY_ORDER="mgbench ssb hits uk ontime taxi coffeeshop tpch tpcds job"

OUT=data.generated.js

{
    echo '// Generated by generate-results.sh from results/*.json and queries/*.sql. Do not edit.'

    # datasets: name + its queries (one per non-empty line of queries/<name>.sql).
    echo -n 'const datasets = ['
    first=1
    for ds in ${QUERY_ORDER}; do
        [ "${first}" = 0 ] && echo -n ','
        first=0
        queries_json="$(jq -R -s 'split("\n") | map(select(length > 0))' "queries/${ds}.sql")"
        printf '\n{"name":"%s","queries":%s}' "${ds}" "${queries_json}"
    done
    echo ''
    echo '];'
    echo ''

    # data: one entry per (system, version). Each entry gets:
    #   system  -- the engine (results/ are ClickHouse; the <engine>/results/ dirs carry it).
    #   source  -- path to the result file, for the "view source" link.
    #   date    -- an aligned timeline date so the systems interleave on one axis: for a
    #              ClickHouse calendar version (major>=18, e.g. 24.3) it is 20YY-MM-15 (the
    #              15th of the release month, not the specific patch's date, which can be a
    #              year later); for older ClickHouse and for the other systems it is the real
    #              release_date. Sorted oldest first (the page re-sorts anyway).
    echo 'const data = ['
    python3 - <<'PY'
import json, glob, re, sys
DIRS = [("results", "ClickHouse"),          # ClickHouse (system injected if absent)
        ("duckdb/results", None),
        ("starrocks/results", None),
        ("cedardb/results", None)]

def aligned_date(system, version, release_date):
    if system == "ClickHouse":
        m = re.match(r'^(\d+)\.(\d+)\.', version or "")
        if m and int(m.group(1)) >= 18:            # YY.minor calendar version -> 20YY-MM-15
            year = 2000 + int(m.group(1))
            month = min(max(int(m.group(2)), 1), 12)
            return f"{year:04d}-{month:02d}-15"
    return release_date or ""

# QUERY_ORDER + per-dataset query counts -> each dataset's [start,end) span in result[].
QUERY_ORDER = "mgbench ssb hits uk ontime taxi coffeeshop tpch tpcds job".split()
span = {}; off = 0
for ds in QUERY_ORDER:
    try:
        n = sum(1 for l in open(f"queries/{ds}.sql") if l.strip())
    except FileNotFoundError:
        continue
    span[ds] = (off, off + n); off += n

entries = []
for d, default_system in DIRS:
    for f in sorted(glob.glob(d + "/*.json")):
        try:
            obj = json.load(open(f))
        except Exception as e:
            print(f"skip {f}: {e}", file=sys.stderr); continue
        if not obj.get("system"):
            obj["system"] = default_system or "Unknown"
        obj["source"] = f
        obj["date"] = aligned_date(obj["system"], obj.get("version",""), obj.get("release_date"))
        entries.append(obj)

# Drop datasets that loaded only a tiny fraction of their real size -- a partial load left
# behind after an engine hit a size cap mid-load (e.g. CedarDB Community Edition's 64 GB limit
# on the 73 GB ssb). Its tables pass a count>0 check so the queries "run", but on a fragment,
# in sub-millisecond time -- meaningless numbers that would slot in as the fastest results.
# Reference = ClickHouse's median size per dataset (it fully loads everything); a reported size
# below 1% of that is a broken load (real partial loads seen at 0.01-0.19%, legit loads all
# >=4%, a 20x gap). Only a STRICTLY POSITIVE reported size counts: StarRocks reports 0 for a
# fully-loaded dataset (columnar size not yet accounted), so 0/absent means "unknown, keep";
# a small nonzero size (CedarDB's fragment) means "partial, drop". Null the dataset's query
# rows and drop its load_time/data_size so it reads as "not loaded" rather than "fastest".
ch_sizes = {}
for o in entries:
    if o["system"] == "ClickHouse":
        for ds, sz in (o.get("data_size") or {}).items():
            if (o.get("load_time") or {}).get(ds) and sz:
                ch_sizes.setdefault(ds, []).append(sz)
ch_ref = {ds: sorted(v)[len(v)//2] for ds, v in ch_sizes.items()}   # median
INCOMPLETE_FRAC = 0.01
dropped = {}
for o in entries:
    ds_sizes = o.get("data_size") or {}
    for ds, (start, end) in span.items():
        ref = ch_ref.get(ds)
        sz = ds_sizes.get(ds)
        if ref and sz and sz < INCOMPLETE_FRAC * ref:
            width = len(o["result"][start]) if start < len(o["result"]) and o["result"][start] else 6
            for i in range(start, min(end, len(o["result"]))):
                o["result"][i] = [None] * width
            (o.get("load_time") or {}).pop(ds, None)
            (o.get("data_size") or {}).pop(ds, None)
            dropped.setdefault(f'{o["system"]} {o.get("version")}', []).append(ds)
for k, v in sorted(dropped.items()):
    print(f"  incomplete-load dropped: {k}: {', '.join(v)}", file=sys.stderr)

# Oldest first; a missing date sorts last. Tie-break by system then version (numeric-aware-ish).
def ver_key(v): return [int(t) if t.isdigit() else t for t in re.split(r'(\d+)', v or "")]
entries.sort(key=lambda o: (o["date"] or "9999-99-99", o["system"], ver_key(o.get("version",""))))

print(",\n".join(json.dumps(o, separators=(",", ":"), sort_keys=True) for o in entries))
print(f"emitted {len(entries)} entries", file=sys.stderr)
PY
    echo '];'
} > "${OUT}"

>&2 echo "wrote ${OUT} ($(wc -c < "${OUT}") bytes)"
