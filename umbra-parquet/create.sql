-- Parquet-direct: define hits as a VIEW over the Athena parquet via the
-- umbra.parquetview table function, with no ingestion into native storage
-- (contrast with ../umbra, which INSERTs the same projection into a table).
-- Column expressions/casts mirror ../umbra/create.sql so the queries are
-- identical; parquetview surfaces CamelCased columns, hence the quoting.
-- The path is the container's /data bind mount (see ./start).
