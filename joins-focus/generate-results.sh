#!/bin/bash -e

# Build data.generated.js (loaded by index.html) from the per-system result files in results/
# and the query sets in queries/.
#
# Output has two consts:
#   const datasets = [{name, queries:[...]}, ...]   // in the QUERY_ORDER the result arrays
#                                                    // are concatenated in
#   const data     = [{system, version, actual_version, release_date, machine, kind,
#                      load_time:{bench:sec}, stats_time:{bench:sec}, data_size:{bench:bytes},
#                      result:[[...]], error:{idx:kind}, error_text:{idx:message},
#                      source, date}]   // date = release_date; the page reads it for sorting
#
# Keeping the data out of index.html (as the main ClickBench page does with
# data.generated.js) keeps the page diffable and lets the data regenerate on its own.
#
#   ./generate-results.sh                 # every result file
#   ./generate-results.sh --passed        # only systems that produced at least one timing
#   ./generate-results.sh --exclude umbra # drop a system by name (repeatable, or comma-separated)
#   ./generate-results.sh --html          # -> report.html, self-contained
#   ./generate-results.sh --html run.html
#
# --html writes a SELF-CONTAINED page instead.
#
# --passed drops a system whose every query row is null.

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "${HERE}"

PASSED="${PASSED:-}"
HTML=""
EXCLUDE="${EXCLUDE:-}"
want_html=""
while [ "$#" -gt 0 ]; do
    arg="$1"
    if [ -n "${want_html}" ]; then HTML="${arg}"; want_html=""; shift; continue; fi
    case "${arg}" in
        --passed) PASSED=1 ;;
        --exclude) EXCLUDE="${EXCLUDE:+${EXCLUDE},}$2"; shift ;;
        --exclude=*) EXCLUDE="${EXCLUDE:+${EXCLUDE},}${arg#--exclude=}" ;;
        --html)   HTML="report.html"; want_html=1 ;;   # an optional filename may follow
        --html=*) HTML="${arg#--html=}" ;;
        -h|--help) sed -n '3,34p' "$0" | sed 's/^#\( \|$\)//'; exit 0 ;;
        *) echo "unknown option: ${arg} (want --passed / --exclude SYSTEM / --html [FILE])" >&2; exit 1 ;;
    esac
    shift
done
export PASSED QUERY_SET EXCLUDE

if [ "${HTML}" = "index.html" ]; then
    echo "refusing to write index.html: it is the page source, and inlining into it is not" >&2
    echo "repeatable (no src tag left to replace on a second run). Pick another name." >&2
    exit 1
fi

# The order every runner concatenates per-benchmark results into result[].
QUERY_ORDER="tpch tpcds job"
# The page shows ONE query text per position, but each system has its own dialect of it. The
# ClickHouse set is used as the canonical text.
QUERY_SET="${QUERY_SET:-clickhouse/queries}"

# In --html mode the JS goes to a temp file and is inlined below.
OUT=data.generated.js
if [ -n "${HTML}" ]; then
    OUT="$(mktemp -t dbb-data.XXXXXX.js)"
    trap 'rm -f "${OUT}"' EXIT
fi

{
    echo '// Generated by generate-results.sh from results/*.json and queries/*.sql. Do not edit.'

    # datasets: name + its queries (one per non-empty line of queries/<name>.sql).
    echo -n 'const datasets = ['
    first=1
    for ds in ${QUERY_ORDER}; do
        [ "${first}" = 0 ] && echo -n ','
        first=0
        queries_json="$(jq -R -s 'split("\n") | map(select(length > 0))' "${QUERY_SET}/${ds}.sql")"
        printf '\n{"name":"%s","queries":%s}' "${ds}" "${queries_json}"
    done
    echo ''
    echo '];'
    echo ''

    # data: one entry per system, read from results/<system>.json (each runner writes its own).
    echo 'const data = ['
    python3 - <<'PY'
import json, glob, os, re, sys

# --exclude / EXCLUDE: drop a system entirely, by name, case-insensitively. Useful when one
# system was not part of a sweep and its newest file is from an older run with a different
# TRIES -- mixing those on one page compares a 1-try number against a 6-try one.
EXCLUDED = {x.strip().lower() for x in os.environ.get("EXCLUDE", "").split(",") if x.strip()}
if EXCLUDED:
    print(f"  excluding: {', '.join(sorted(EXCLUDED))}", file=sys.stderr)

# QUERY_ORDER + per-benchmark query counts -> each benchmark's [start,end) span in result[].
QUERY_ORDER = "tpch tpcds job".split()
span = {}; off = 0
for ds in QUERY_ORDER:
    try:
        n = sum(1 for l in open(f"{os.environ.get('QUERY_SET', 'clickhouse/queries')}/{ds}.sql") if l.strip())
    except FileNotFoundError:
        continue
    span[ds] = (off, off + n); off += n
TOTAL = off

# Each run writes its own timestamped file, so a system can have several -- one per benchmark,
# or repeated runs of the same one. Group by system and fold them into a single entry: for each
# benchmark, take its rows from the NEWEST file that actually has timings there, and its
# load_time/data_size from that same file. Ordering is by mtime, so it also copes with the older
# untimestamped results/<system>.json files.
# results/<system>/<timestamp>.json is the layout each runner writes. The flat
# results/<system>.json form predates it and is still read, so older runs are not orphaned.
files = glob.glob("results/*/*.json") + glob.glob("results/*.json")
runs = {}
for f in sorted(files, key=lambda x: os.path.getmtime(x)):
    try:
        obj = json.load(open(f))
    except Exception as e:
        print(f"skip {f}: {e}", file=sys.stderr); continue
    if not obj.get("system"):
        print(f"skip {f}: no 'system' field", file=sys.stderr); continue
    if obj["system"].lower() in EXCLUDED:
        continue
    n = len(obj.get("result") or [])
    if n != TOTAL:
        print(f"  WARNING {f}: result[] has {n} rows, expected {TOTAL} -- skipping, it cannot be "
              f"aligned by offset", file=sys.stderr)
        continue
    runs.setdefault(obj["system"], []).append((f, obj))


# Per-query FAILURE REASONS, read from the run's own log. Each runner writes
# logs/<system>/<run timestamp>.log named for the same timestamp as its results file, so a log
# pairs with exactly the run whose rows are being used -- no guessing. Rows that a run did not
# time carry a reason here; the page shows it instead of a bare skull.
#
# The query number in a log line is the GLOBAL 1-based position across all three benchmarks
# (q1..q238), so the result[] index is N-1. That is how "q60 [tpcds]" is TPC-DS q38.
FAIL_RE = re.compile(r'^q(\d+) \[(\w+)\]: (FAILED|SKIPPED)(.*)$')

def classify(msg):
    """Failure kind from the runner's own message. Patterns taken from real log text, not
    guessed: Firebolt writes 'EXCEPT is not supported' and 'Operation timed out after ...',
    ClickHouse 'memory limit exceeded' and 'server died mid-query'."""
    m = msg.lower()
    if 'skipped (not loaded)' in m:                                   return 'not_loaded'
    if 'server died' in m:                                            return 'crash'
    # 'unable to allocate' / 'memory is exhausted' is CedarDB: "unable to allocate working
    # memory (8192 MB requested) HINT: Working memory is exhausted. Increase `workmemsize`".
    if ('memory limit exceeded' in m or 'memory_limit_exceeded' in m
            or 'out of memory' in m or 'mem_limit' in m
            or 'memory limit' in m or 'unable to allocate' in m
            or 'memory is exhausted' in m):                           return 'oom'
    if ('timeout' in m or 'timed out' in m or 'rc=124' in m
            or 'rc=28' in m):                                         return 'timeout'
    # 'not YET supported' is Firebolt's wording for both a missing operator ("INTERSECT is not
    # yet supported") and a missing overload ("Function signature 'stddev_samp(bigint)' not yet
    # supported"), so a literal 'not supported' test misses all of them.
    if (re.search(r'not (yet )?supported', m) or 'unsupported' in m
            or 'not_implemented' in m or 'unknown function' in m
            or 'syntax error' in m):                                  return 'unsupported'
    return 'other'

def log_reasons(system, result_file):
    """{global index: (kind, message)} from the log paired with this result file, or {}."""
    base = os.path.basename(result_file)
    if not base.endswith('.json'): return {}
    logf = os.path.join('logs', system.lower(), base[:-5] + '.log')
    if not os.path.exists(logf): return {}
    out = {}
    with open(logf, errors='replace') as fh:
        for line in fh:
            m = FAIL_RE.match(line)
            if not m: continue
            idx = int(m.group(1)) - 1
            if idx in out: continue                    # first mention wins
            msg = (m.group(3) + m.group(4)).strip()
            out[idx] = (classify(msg), msg[:300])
    return out

def ran(row):
    return isinstance(row, list) and any(v is not None for v in row)

entries = []
for system, rs in runs.items():
    base = dict(rs[-1][1])                      # newest run supplies the scalar fields
    width = max((len(r) for _, o in rs for r in o["result"] if isinstance(r, list)), default=6)
    base["result"] = [[None] * width for _ in range(TOTAL)]
    base["load_time"], base["data_size"], base["stats_time"] = {}, {}, {}
    base["error"], base["error_text"] = {}, {}
    used = {}
    for ds, (start, end) in span.items():
        for f, o in reversed(rs):               # newest first
            rows = o["result"][start:end]
            if any(ran(r) for r in rows):
                base["result"][start:end] = rows
                # stats_time travels with load_time: both describe the run that produced these
                # rows, so taking them from the same file is what keeps them consistent. It is
                # separate from load_time because statistics collection is not loading -- see the
                # runners; folding them together made a STATISTICS=1 load_time incomparable.
                for k in ("load_time", "data_size", "stats_time"):
                    v = (o.get(k) or {}).get(ds)
                    if v is not None: base[k][ds] = v
                # Reasons for this benchmark's untimed rows, from THIS file's log. Only attached
                # where the row really has no timing, so a log/result mismatch cannot label a
                # query that actually ran.
                reasons = log_reasons(system, f)
                for i in range(start, end):
                    if i in reasons and not ran(base["result"][i]):
                        kind, msg = reasons[i]
                        base["error"][str(i)] = kind
                        base["error_text"][str(i)] = msg
                used[ds] = f[len("results/"):] if f.startswith("results/") else f
                break
    base["source"] = sorted(set(used.values())) or [rs[-1][0]]
    if len(rs) > 1:
        detail = ", ".join(f"{ds}<-{f}" for ds, f in sorted(used.items())) or "none"
        print(f"  {system}: combined {len(rs)} runs ({detail})", file=sys.stderr)
    if base["error"]:
        from collections import Counter
        c = Counter(base["error"].values())
        print(f"  {system}: failure reasons: " +
              ", ".join(f"{k}={v}" for k, v in sorted(c.items())), file=sys.stderr)
    entries.append(base)

for obj in entries:
    # index.html reads `elem.date || elem.release_date` and sorts on `date`. The versions
    # benchmark computed `date` as an aligned timeline date so many versions of many systems
    # would interleave on one axis; with one version per system that collapses to the release
    # date itself.
    obj["date"] = obj.get("release_date") or ""

# Drop a benchmark that loaded only a tiny fraction of its real size -- a partial load left
# behind after a system hit a size cap mid-load (CedarDB Community Edition caps total data).
# Its tables pass a count>0 check so the queries "run", but on a fragment, in sub-millisecond
# time -- meaningless numbers that would slot in as the fastest results. Reference = ClickHouse's
# size for that benchmark (it loads everything); below 1% of that is a broken load. Only a
# STRICTLY POSITIVE reported size counts: StarRocks reports 0 for a fully-loaded benchmark
# (columnar size not yet accounted), so 0/absent means "unknown, keep", while a small nonzero
# size means "partial, drop". Null the benchmark's rows and drop its load_time/data_size so it
# reads as "not loaded" rather than "fastest".
ch_ref = {}
for o in entries:
    if o["system"] == "ClickHouse":
        for ds, sz in (o.get("data_size") or {}).items():
            if (o.get("load_time") or {}).get(ds) and sz:
                ch_ref[ds] = sz
INCOMPLETE_FRAC = 0.01
dropped = {}
for o in entries:
    ds_sizes = o.get("data_size") or {}
    for ds, (start, end) in span.items():
        ref, sz = ch_ref.get(ds), ds_sizes.get(ds)
        if ref and sz and sz < INCOMPLETE_FRAC * ref:
            r = o["result"]
            width = len(r[start]) if start < len(r) and r[start] else 6
            for i in range(start, min(end, len(r))):
                r[i] = [None] * width
            (o.get("load_time") or {}).pop(ds, None)
            (o.get("data_size") or {}).pop(ds, None)
            dropped.setdefault(o["system"], []).append(ds)
for k, v in sorted(dropped.items()):
    print(f"  incomplete-load dropped: {k}: {', '.join(v)}", file=sys.stderr)

def has_timings(o):
    return any(v is not None for row in o["result"] if row for v in row)

if os.environ.get("PASSED"):
    kept = []
    for o in entries:
        if has_timings(o):
            kept.append(o)
        else:
            print(f"  no-timings skipped: {o['system']}", file=sys.stderr)
    entries = kept

entries.sort(key=lambda o: (o["date"] or "9999-99-99", o["system"].lower()))

print(",\n".join(json.dumps(o, separators=(",", ":"), sort_keys=True) for o in entries))
print(f"emitted {len(entries)} entries", file=sys.stderr)
PY
    echo '];'
} > "${OUT}"

if [ -n "${HTML}" ]; then
    # Replace the external-script tag with the data inlined, leaving the rest of the page byte
    # for byte. Fails loudly if the tag is not found, rather than emitting a page with no data.
    awk -v datafile="${OUT}" '
        /<script[^>]*src="data\.generated\.js"><\/script>/ {
            print "<script type=\"text/javascript\">"
            while ((getline line < datafile) > 0) print line
            close(datafile)
            print "</script>"
            found = 1
            next
        }
        { print }
        END { if (!found) { print "data.generated.js script tag not found in index.html" > "/dev/stderr"; exit 1 } }
    ' index.html > "${HTML}" || { rm -f "${HTML}"; exit 1; }
    >&2 echo "wrote ${HTML} ($(wc -c < "${HTML}") bytes, self-contained; data.generated.js untouched)"
else
    >&2 echo "wrote ${OUT} ($(wc -c < "${OUT}") bytes)"
fi
